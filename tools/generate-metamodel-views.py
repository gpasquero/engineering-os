#!/usr/bin/env python3
"""Generate three graph views of the Engineering OS metamodel.

Reads:  model/metamodel/entities/*.md   (relationship tables)
        model/metamodel/ontology/*.ttl  (class hierarchy, object properties)
Writes: model/metamodel/views/*.md      (Mermaid graphs + structural metrics)

These are DERIVED artifacts (ADR-0012). Do not edit the output by hand; edit
the sources and regenerate. This is the first mechanically generated projection
in the repository (ISSUE-0037).

Semantic Layer: None — cross-cutting infrastructure (ADR-0039).
"""
import re
import sys
import pathlib
import itertools
import collections

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENTITIES = ROOT / "model/metamodel/entities"
TTL = ROOT / "model/metamodel/ontology/engineering-os-metamodel.ttl"
OUT = ROOT / "model/metamodel/views"

BANNER = (
    "> **Generated by `tools/generate-metamodel-views.py`. Do not edit.**\n"
    "> A derived artifact (`ADR-0012`). Edit the sources and regenerate.\n"
)


# --------------------------------------------------------------------------
# Sources
# --------------------------------------------------------------------------
def read_entities():
    """entity name -> {'family':..., 'rels':[(relation, target, cardinality)]}"""
    out = {}
    for path in sorted(ENTITIES.glob("*.md")):
        text = path.read_text()
        title = re.search(r"^title:\s*(\S+)", text, re.M)
        family = re.search(r"^entity-family:\s*(\S+)", text, re.M)
        if not title:
            continue
        rels = []
        section = re.search(r"^## relationships\n(.*?)(?=^## )", text, re.M | re.S)
        if section:
            for row in re.findall(r"^\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]*?)\s*\|",
                                  section.group(1), re.M):
                rel, target, card = (c.strip() for c in row)
                if rel in ("Relationship", "---") or set(rel) <= {"-"}:
                    continue
                rels.append((rel, target, card))
        out[title.group(1)] = {
            "family": family.group(1) if family else "unassigned",
            "rels": rels,
            "file": path.name,
        }
    return out


def read_ttl():
    """Returns (subclass_edges, property_edges, kinds). Parsed, not pattern-matched."""
    import rdflib
    from rdflib.namespace import OWL, RDF, RDFS

    g = rdflib.Graph()
    g.parse(TTL, format="turtle")
    EOS = rdflib.Namespace("https://example.org/engineering-os/metamodel#")

    def local(node):
        return str(node)[len(str(EOS)):] if str(node).startswith(str(EOS)) else None

    kinds = {}
    for c in g.subjects(RDF.type, OWL.Class):
        if local(c):
            kinds[local(c)] = "class"
    for t in (OWL.ObjectProperty, OWL.DatatypeProperty):
        for p in g.subjects(RDF.type, t):
            if local(p):
                kinds[local(p)] = "property"

    subclass = [(local(c), local(s))
                for c, s in g.subject_objects(RDFS.subClassOf)
                if local(c) and local(s)]

    def domains_of(p):
        """Named domain, or the members of an owl:unionOf domain."""
        out = []
        for d in g.objects(p, RDFS.domain):
            if local(d):
                out.append(local(d))
            else:
                for u in g.objects(d, OWL.unionOf):
                    out += [local(m) for m in rdflib.collection.Collection(g, u) if local(m)]
        return out

    props = []
    for p in g.subjects(RDF.type, OWL.ObjectProperty):
        if not local(p):
            continue
        ranges = [local(r) for r in g.objects(p, RDFS.range) if local(r)]
        for d in domains_of(p):
            for r in ranges:
                props.append((d, local(p), r))

    return subclass, props, kinds


